// =============================================================================
// services/media/youtube.js — the browser's ONE call into POST /api/media/youtube
//
// OWNER: A38 (Wave 4). Responsibility:
//   INPUT   the pasted YouTube URL (+ optional title / caption language)
//   OUTPUT  a promise resolving to the ingested source object, so a page can
//           add a video to the library exactly the way it adds a PDF
//   DEPENDS ON frontend/js/api.js (`apiPost` — the only module allowed to
//           fetch) and nothing else. No direct network calls from here.
//   HONEST RULE: every failure is reported with the server's own plain message.
//           This module NEVER invents a transcript, a duration, or a summary.
//
// Mounting note for the page agent: render into a PAGE-PREFIXED hook
// (`data-library-video`, `data-session-video`, …). Never a bare
// `[data-content]` — `components/shell.js` owns that one, and writing into it
// erases the shell's <main>. See docs/HANDOFF.md (A30's finding).
//
// Public interface (documented for A23/A24 and anyone else adding video import):
//   YOUTUBE_ENDPOINT                  the contract path, in one place
//   looksLikeYouTubeUrl(value)        → boolean (a pre-check only; the server decides)
//   importYouTubeVideo(url, opts?)    → { source, language, isAutoGenerated, … }
//   youtubeImportError(error)        → a sentence a student can act on
//   describeTranscriptImport(result)  → a one-line honest summary of what was read
// =============================================================================

import { apiPost } from '../../api.js';

/** Contract path for video ingestion (docs/API_CONTRACT.md v2.0). */
export const YOUTUBE_ENDPOINT = '/api/media/youtube';

/** YouTube's own hosts. A link on any other host is not a YouTube video. */
const YOUTUBE_HOSTS = new Set([
  'youtube.com', 'www.youtube.com', 'm.youtube.com', 'music.youtube.com',
  'youtu.be', 'www.youtu.be',
  'youtube-nocookie.com', 'www.youtube-nocookie.com',
]);

/** A YouTube video id is 11 characters of the URL-safe alphabet. */
const VIDEO_ID_PATTERN = /^[A-Za-z0-9_-]{11}$/;

// watch?v=ID (query), and the /shorts, /embed, /live, /v forms (path segment).
const PATH_MODES = new Map([
  ['watch', 'query'],
  ['shorts', 'segment'],
  ['embed', 'segment'],
  ['live', 'segment'],
  ['v', 'segment'],
]);

/**
 * A cheap, optimistic pre-check so a paste box can say "that doesn't look like a
 * YouTube link" BEFORE a round trip.
 *
 * ⚠️ This is NOT the validation authority: the server re-checks the scheme, the
 * host and the video id and answers 400 INVALID_URL when they are wrong. Keep
 * this one permissive-ish and never block a submit on it — a rejected paste is
 * the server's message to show, not this function's.
 */
export function looksLikeYouTubeUrl(value) {
  if (typeof value !== 'string') return false;
  const trimmed = value.trim();
  if (trimmed === '' || trimmed.length > 2048) return false;

  // A student often pastes without "https://".
  const hasScheme = /^[a-z][a-z0-9+.-]*:/i.test(trimmed);
  let parsed;
  try {
    parsed = new URL(hasScheme ? trimmed : `https://${trimmed}`);
  } catch {
    return false;
  }
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') return false;

  const host = parsed.hostname.toLowerCase();
  if (!YOUTUBE_HOSTS.has(host)) return false;

  const parts = parsed.pathname.split('/').filter((part) => part !== '');
  const mode = PATH_MODES.get(parts[0] ?? '');
  if (mode === 'query') return VIDEO_ID_PATTERN.test(parsed.searchParams.get('v') ?? '');
  if (mode === 'segment') return VIDEO_ID_PATTERN.test(parts[1] ?? '');
  if (host === 'youtu.be' || host === 'www.youtu.be') return VIDEO_ID_PATTERN.test(parts[0] ?? '');
  return false;
}

/**
 * Ingest a video: the server reads its captions, chunks them, embeds them and
 * stores them as a searchable, citable source.
 *
 * @param {string} url                  the pasted YouTube link
 * @param {object} [options]
 * @param {string} [options.title]      override the video's own title (≤160 chars)
 * @param {string} [options.language]   preferred caption language, e.g. "en", "pt-BR"
 * @param {number} [options.timeoutMs]  captions + embedding take longer than a chat turn
 * @returns {Promise<{source: object, language: string, isAutoGenerated: boolean,
 *                    segmentCount: number, textChars: number}>}
 * @throws an ApiError from api.js — pass it to `youtubeImportError` / `errorMessage`
 */
export async function importYouTubeVideo(url, options = {}) {
  const { title, language, timeoutMs } = options ?? {};
  const body = { url };
  if (title !== undefined) body.title = title;
  if (language !== undefined) body.language = language;
  return apiPost(YOUTUBE_ENDPOINT, body, timeoutMs ? { timeoutMs } : undefined);
}

/* -------------------------------------------------------------- error copy */

// The honest-degradation sentence for each failure the server can report. The
// server's own message is preferred wherever it has one — it is the specific,
// plain explanation (why the captions were missing, which host was refused).
// A 404 means this build's server has no /api/media route mounted, which is the
// same "not available yet" shape material-import.js uses for OCR.
const UNAVAILABLE_MESSAGE = 'Video import isn’t available on this server yet. '
  + 'Add a document or a web page instead.';

const ERROR_FALLBACKS = {
  INVALID_URL: 'That isn’t a YouTube video link. Paste a youtube.com/watch, youtu.be or youtube.com/shorts link.',
  VALIDATION_ERROR: 'Check the link and try again.',
  NO_TRANSCRIPT: 'That video has no captions to read, so there is nothing to study from it. '
    + 'Try a video with subtitles.',
  FETCH_FAILED: 'YouTube couldn’t be reached just now. Try again in a moment.',
  NIM_ERROR: 'The embedding service failed, so nothing was saved. Try again in a moment.',
  CHROMA_UNAVAILABLE: 'The search index is unavailable, so nothing was saved. Try again in a moment.',
};

/**
 * One sentence for the student. Prefers the server's message (it names the
 * real reason), falls back to the code above, and never pretends a transcript
 * was read when it was not.
 */
export function youtubeImportError(error) {
  if (error?.code === 'NOT_FOUND' || error?.status === 404) return UNAVAILABLE_MESSAGE;
  const serverMessage = error?.message;
  if (typeof serverMessage === 'string' && serverMessage.trim() !== '') return serverMessage.trim();
  const code = error?.code;
  if (code && ERROR_FALLBACKS[code]) return ERROR_FALLBACKS[code];
  return 'The video could not be added. Try again in a moment.';
}

/* -------------------------------------------------------- success summary */

/** "39 passages · 21,538 characters of captions · en" — what was actually read. */
export function describeTranscriptImport(result) {
  if (!result) return '';
  const parts = [];
  if (typeof result.segmentCount === 'number' && result.segmentCount > 0) {
    parts.push(`${result.segmentCount} passage${result.segmentCount === 1 ? '' : 's'}`);
  }
  if (typeof result.textChars === 'number' && result.textChars > 0) {
    parts.push(`${result.textChars.toLocaleString()} characters of captions`);
  }
  if (typeof result.language === 'string' && result.language !== '') {
    parts.push(result.isAutoGenerated ? `${result.language} (auto-generated)` : result.language);
  }
  return parts.join(' · ');
}
