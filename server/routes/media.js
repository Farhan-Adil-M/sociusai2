// =============================================================================
// routes/media.js — POST /api/media/youtube
//
// OWNER: A38 (Wave 4). A student pastes a YouTube URL; the SERVER (never the
// browser) reads the video's captions, turns them into timestamped passages and
// ingests them as a normal source: extract → chunk → embed → store → record.
// The result is citable, so a tutor answer can point at the exact second of the
// video.
//
// Per-user: `requireAuth` runs first, so an anonymous request is 401 before any
// handler, and every write pins `user_id = req.userId` (the verified id — never
// a client-supplied one).
//
// Contract (docs/API_CONTRACT.md v2.0, `POST /api/media/youtube`):
//   request   { url, title?, language? }
//   response  201 { source: { …, type: "youtube", durationSeconds, sizeLabel },
//                  language, isAutoGenerated, segmentCount, textChars }
//   errors    400 INVALID_URL / VALIDATION_ERROR · 422 NO_TRANSCRIPT
//             502 FETCH_FAILED / NIM_ERROR · 503 CHROMA_UNAVAILABLE
//
// Error-code note for a maintainer: this route deliberately follows the
// CONTRACT and the existing house precedent (server/services/extract/webpage.js
// throws INVALID_URL for "must start with http:// or https://") — a rejected URL
// is `400 INVALID_URL`, while a missing/blank `url`, an over-long `title` or a
// malformed `language` is `400 VALIDATION_ERROR`. Consumers only branch on the
// HTTP status, so nothing changes for them. Recorded in docs/HANDOFF.md.
// =============================================================================

import express from 'express';
import path from 'node:path';
import multer from 'multer';
import { config } from '../config.js';
import { ApiError } from '../middleware/errors.js';
import { requireAuth } from '../middleware/auth.js';
import { fetchYouTubeTranscript } from '../services/media/youtube.js';
import { extractImage } from '../services/extract/image.js';
import { embedTexts } from '../services/embeddings.js';
import { addChunks, deleteChunks } from '../store/vectorStore.js';
import { persistSource } from './sources.js';
import { logActivity } from '../store/sqlite.js';

/* ------------------------------------------------------------- validation */

// `title` is optional and falls back to the video's own title, so its cap is
// the same 160 characters used by every other source title.
const MAX_TITLE_CHARS = 160;
// `language` is an optional caption-language preference, e.g. "en" or "pt-BR".
const LANGUAGE_PATTERN = /^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})?$/;

function readRequest(body) {
  const { url, title, language } = body ?? {};

  if (typeof url !== 'string' || url.trim() === '') {
    throw new ApiError(400, 'VALIDATION_ERROR', 'Paste a YouTube video link in "url".');
  }
  if (title !== undefined && (typeof title !== 'string' || title.trim().length > MAX_TITLE_CHARS)) {
    throw new ApiError(400, 'VALIDATION_ERROR', `Title must be at most ${MAX_TITLE_CHARS} characters.`);
  }
  if (language !== undefined
      && (typeof language !== 'string' || language.trim() === '' || !LANGUAGE_PATTERN.test(language.trim()))) {
    throw new ApiError(400, 'VALIDATION_ERROR', 'language must be a caption language code such as "en" or "pt-BR".');
  }

  return {
    url: url.trim(),
    titleOverride: typeof title === 'string' && title.trim() !== '' ? title.trim() : null,
    language: typeof language === 'string' ? language.trim() : undefined,
  };
}

/* ------------------------------------------------------------- persistence */

/** "8:32 video" for a 512-second video — the contract's YouTube sizeLabel.
 *  Mirrors the duration formatter in sources.js (not exported from there). */
function videoSizeLabel(seconds) {
  const total = Math.floor(Number(seconds));
  if (!Number.isFinite(total) || total < 0) return 'video';
  const minutes = Math.floor(total / 60);
  const pad = (value) => String(value).padStart(2, '0');
  const clock = minutes < 60
    ? `${minutes}:${pad(total % 60)}`
    : `${Math.floor(minutes / 60)}:${pad(minutes % 60)}:${pad(total % 60)}`;
  return `${clock} video`;
}

/* ------------------------------------------------------------------ router */

export function mediaRouter({ db, ai, vector, auth }) {
  const router = express.Router();
  const embed = ai?.embedTexts ?? embedTexts;
  const store = vector?.addChunks ?? addChunks;
  const remove = vector?.deleteChunks ?? deleteChunks;

  // Private by contract: anonymous → 401 before any handler runs.
  router.use(requireAuth({ auth, db }));

  // POST /api/media/youtube
  router.post('/youtube', async (req, res) => {
    const { url, titleOverride, language } = readRequest(req.body ?? {});
    const userId = req.userId; // the verified id — never a client-supplied one

    // Captions only. No API key exists and none is allowed to be added, so this
    // is the honest path; every failure mode is a specific error code.
    const transcript = await fetchYouTubeTranscript({ url, language });
    const title = titleOverride ?? transcript.title.slice(0, MAX_TITLE_CHARS);

    // One implementation of ingest, shared with `POST /api/sources/upload` —
    // this route used to carry a ~100-line private copy of the same pipeline
    // (chunk → embed → model guard → vector store → atomic batch →
    // compensation). `persistSource` now also writes the v8 `media_assets` row
    // in the same atomic batch, so a video source can never exist without its
    // media record.
    const persisted = await persistSource(db, {
      type: 'youtube',
      title,
      url,
      segments: transcript.segments,
      pageCount: null,
      slideCount: null,
      durationSeconds: transcript.durationSeconds,
      media: { kind: 'youtube', durationSeconds: transcript.durationSeconds, textChars: transcript.charCount },
      userId,
    }, { embed, store, remove });

    await logActivity(
      db,
      'upload',
      null,
      `${title} (${videoSizeLabel(transcript.durationSeconds)}${transcript.isAutoGenerated ? ', auto captions' : ''})`,
      null,
      userId,
    );

    res.status(201).json({
      source: persisted,
      language: transcript.language,
      isAutoGenerated: transcript.isAutoGenerated,
      segmentCount: transcript.segments.length,
      textChars: transcript.charCount,
    });
  });

  // -------------------------------------------------------------------------
  // POST /api/media/ocr — image → text (Wave 4, A39). Long unwired: A39 owned
  // no route file, so the service was built and proven but returned 404. This
  // is the missing seam. A23's `material-import.js` already posts exactly
  // `file` + `ingest=1` here and reads `data.source` back.
  // -------------------------------------------------------------------------
  const IMAGE_EXT = /\.(png|jpe?g|webp)$/i;
  const uploadImage = multer({
    storage: multer.memoryStorage(),
    limits: { fileSize: config.maxUploadMb * 1024 * 1024, files: 1 },
    fileFilter: (req, file, cb) => {
      if (!IMAGE_EXT.test(path.extname(file.originalname ?? '').toLowerCase())) {
        return cb(new ApiError(400, 'UNSUPPORTED_FILE', 'Only .png, .jpg, and .webp images can be read for text.'));
      }
      cb(null, true);
    },
  });

  router.post('/ocr', (req, res, next) => uploadImage.single('file')(req, res, (err) => {
    if (err?.code === 'LIMIT_FILE_SIZE') {
      return next(new ApiError(413, 'FILE_TOO_LARGE',
        `This file is too large — the upload limit is ${config.maxUploadMb} MB.`));
    }
    return next(err);
  }), async (req, res) => {
    if (!req.file) throw new ApiError(400, 'VALIDATION_ERROR', 'Attach one image in the "file" field.');
    const ingest = String(req.body?.ingest ?? '') === '1';

    // `extractImage` owns ALL validation — size, extension, MIME, magic bytes,
    // pixel dimensions — and throws 413 FILE_TOO_LARGE / 400 UNSUPPORTED_FILE
    // itself. Do not re-validate here; two guards drift.
    const { segments, ocr } = await extractImage(req.file.buffer, {
      originalname: req.file.originalname,
      mimetype: req.file.mimetype,
      size: req.file.size,
    });

    // `ocr` is the only extra field; persistSource ignores it. It MUST be
    // echoed — the student has to know when a read may be unreliable.
    const body = {
      text: ocr.text, charCount: ocr.charCount, language: ocr.language,
      confidence: ocr.confidence, reliability: ocr.reliability, note: ocr.note,
      lineCount: ocr.lineCount, unreliableLines: ocr.unreliableLines, durationMs: ocr.durationMs,
    };

    if (!ingest) return res.json(body);

    const title = path.basename(String(req.file.originalname ?? 'image')).slice(0, 160);
    const source = await persistSource(db, {
      type: 'image',
      title,
      url: null,
      segments,
      pageCount: null,
      slideCount: null,
      media: { kind: 'image', textChars: ocr.charCount },
      userId: req.userId,
    }, { embed, store, remove });

    await logActivity(db, 'upload', null, `${title} (image)`, null, req.userId);
    return res.status(201).json({ ...body, source });
  });

  return router;
}
